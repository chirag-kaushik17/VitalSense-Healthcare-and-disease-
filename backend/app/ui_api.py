@router.get("/patients/search")
def search_patients(
    q: str = "",
    sex: str | None = None,
    category: Literal["low", "moderate", "high"] | None = None,
    sort: Literal["risk_score", "age", "mrn"] = "mrn",
    order: Literal["asc", "desc"] = "asc",
    limit: int = Query(25, ge=1, le=100),
    offset: int = Query(0, ge=0),
    db: Session = Depends(get_db),
) -> dict[str, Any]:
    snapshot = _get_snapshot(db)
    normalized_query = q.casefold()
    filtered = [row for row in snapshot["rows"] if (
        not normalized_query
        or row["mrn"].casefold().startswith(normalized_query)
        or str(row["id"]).casefold().startswith(normalized_query)
    )]
    if sex:
        filtered = [row for row in filtered if row["sex"].casefold() == sex.casefold()]
    if category:
        filtered = [row for row in filtered if row["risk_category"] == category]
    filtered.sort(key=lambda row: (row[sort] is None, row[sort] if sort != "mrn" else row[sort].casefold()), reverse=order == "desc")
    total = len(filtered)
    return {
        "total": total,
        "items": [{key: row[key] for key in (
            "id", "mrn", "age", "sex", "ethnicity", "smoking_status", "risk_score", "risk_category", "condition_count"
        )} for row in filtered[offset:offset + limit]],
    }


@router.get("/patients/{patient_id}/history")
def patient_history(patient_id: UUID, db: Session = Depends(get_db)) -> dict[str, Any]:
    if db.get(Patient, patient_id) is None:
        raise HTTPException(status_code=404, detail="Patient not found")

    vitals = list(db.scalars(
        select(Vital).where(Vital.patient_id == patient_id).order_by(Vital.measured_at.desc()).limit(40)
    ))
    vitals.reverse()
    lab_rows = list(db.scalars(
        select(LabResult)
        .where(LabResult.patient_id == patient_id, LabResult.test_code.in_(list(LAB_RANGES)))
        .order_by(LabResult.measured_at.desc())
    ))
    labs: dict[str, list[dict[str, Any]]] = {}
    for lab in lab_rows:
        name = LAB_RANGES[lab.test_code]["name"]
        values = labs.setdefault(name, [])
        if len(values) < 20:
            values.append({
                "measured_at": _as_json(lab.measured_at),
                "value": float(lab.value),
                "unit": lab.unit,
                "reference_low": float(lab.reference_low) if lab.reference_low is not None else LAB_RANGES[lab.test_code]["low"],
                "reference_high": float(lab.reference_high) if lab.reference_high is not None else LAB_RANGES[lab.test_code]["high"],
            })
    encounters = list(db.scalars(
        select(Encounter).where(Encounter.patient_id == patient_id).order_by(Encounter.started_at.desc()).limit(15)
    ))
    conditions = list(db.scalars(
        select(Condition).where(Condition.patient_id == patient_id).order_by(Condition.recorded_at.desc()).limit(50)
    ))
    return {
        "vitals": [_as_json({key: getattr(item, key) for key in (
            "measured_at", "heart_rate", "systolic_bp", "diastolic_bp", "respiratory_rate", "temperature_c", "oxygen_saturation"
        )}) for item in vitals],
        "labs": labs,
        "encounters": [_as_json({key: getattr(item, key) for key in (
            "encounter_type", "started_at", "ended_at", "reason"
        )}) for item in encounters],
        "conditions": [_as_json({key: getattr(item, key) for key in (
            "display", "recorded_at", "status"
        )}) for item in conditions],
    }


@router.get("/meta/tables")
def table_metadata(db: Session = Depends(get_db)) -> dict[str, Any]:
    inspector = inspect(db.get_bind())
    tables = []
    relationships = []
    for table_name, model in TABLE_MODELS.items():
        columns = []
        primary_keys = set(inspector.get_pk_constraint(table_name).get("constrained_columns") or [])
        foreign_keys = inspector.get_foreign_keys(table_name)
        fk_columns = {}
        for foreign_key in foreign_keys:
            referred_table = foreign_key.get("referred_table")
            referred_columns = foreign_key.get("referred_columns") or []
            for local_column, referred_column in zip(foreign_key.get("constrained_columns") or [], referred_columns):
                fk_columns[local_column] = f"{referred_table}.{referred_column}"
            if referred_table:
                relationships.append({
                    "from": table_name,
                    "to": referred_table,
                    "type": "many-to-one",
                    "on_delete": str(foreign_key.get("options", {}).get("ondelete", "NO ACTION")).upper(),
                })
        for column in inspector.get_columns(table_name):
            name = column["name"]
            columns.append({
                "name": name,
                "type": str(column["type"]),
                "nullable": bool(column["nullable"]),
                "primary_key": name in primary_keys,
                "foreign_key": fk_columns.get(name),
                "description": COLUMN_INFO.get(table_name, {}).get(name, "No additional lineage recorded."),
            })
        tables.append({
            "name": table_name,
            "description": TABLE_INFO[table_name]["description"],
            "row_count": db.scalar(select(func.count()).select_from(model)) or 0,
            "columns": columns,
            "indexes": inspector.get_indexes(table_name),
            "source": TABLE_INFO[table_name]["source"],
        })
    return {"tables": tables, "relationships": relationships}


@router.get("/meta/tables/{name}/sample")
def table_sample(
    name: str,
    limit: int = Query(5, ge=1, le=10),
    db: Session = Depends(get_db),
) -> dict[str, Any]:
    model = TABLE_MODELS.get(name)
    if model is None:
        raise HTTPException(status_code=404, detail="Table not found")
    primary_key = list(model.__table__.primary_key.columns)
    statement = select(model).order_by(*primary_key).limit(limit)
    rows = db.scalars(statement)
    return {"name": name, "items": [
        _as_json({column.key: getattr(row, column.key) for column in model.__table__.columns})
        for row in rows
    ]}


