def invalidate_snapshot() -> None:
    global _SNAPSHOT
    with _SNAPSHOT_LOCK:
        _SNAPSHOT = None


def _as_json(value: Any) -> Any:
    if isinstance(value, (UUID, date, datetime)):
        return value.isoformat() if not isinstance(value, UUID) else str(value)
    if isinstance(value, Decimal):
        return float(value)
    if isinstance(value, dict):
        return {str(key): _as_json(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_as_json(item) for item in value]
    if isinstance(value, np.generic):
        return value.item()
    return value


def _age(patient: Patient, encounter_dates: dict[UUID, datetime]) -> int:
    latest = encounter_dates.get(patient.id)
    if latest is None:
        return 65
    return max(0, int(((latest.date() - patient.date_of_birth).days) / 365.25))


def _category_counts(items: list[dict[str, Any]]) -> dict[str, int]:
    return {
        category: sum(item["risk_category"] == category for item in items)
        for category in ("low", "moderate", "high")
    }


def _get_snapshot(db: Session, refresh: bool = False) -> dict[str, Any]:
    global _SNAPSHOT
    with _SNAPSHOT_LOCK:
        if refresh:
            _SNAPSHOT = None
        if _SNAPSHOT is not None:
            return _SNAPSHOT

        cache = get_risk_cache(db, refresh=refresh)
        patients = cache["patients"]
        patient_map = {patient.id: patient for patient in patients}
        conditions = list(db.scalars(select(Condition).order_by(Condition.recorded_at.desc())))
        condition_counts: dict[UUID, int] = {}
        active_conditions: dict[str, set[UUID]] = {}
        for condition in conditions:
            condition_counts[condition.patient_id] = condition_counts.get(condition.patient_id, 0) + 1
            if condition.status != "resolved":
                active_conditions.setdefault(condition.display, set()).add(condition.patient_id)

        rows = []
        for patient_id in cache["patient_ids"]:
            patient = patient_map[patient_id]
            risk = cache["default_scores"][patient_id]
            rows.append({
                "id": patient_id,
                "mrn": patient.mrn or "",
                "age": _age(patient, cache["encounter_dates"]),
                "sex": patient.sex,
                "ethnicity": patient.ethnicity or "unknown",
                "smoking_status": patient.smoking_status or "unknown",
                "risk_score": risk["risk_score"],
                "risk_category": risk["risk_category"],
                "own_risk": cache["own_risk"].get(patient_id, 0.0),
                "neighbor_fraction": risk["neighbor_fraction"],
                "out_of_range": cache["out_of_range"].get(patient_id, []),
                "condition_count": condition_counts.get(patient_id, 0),
            })

        counts = {
            "patient_count": len(patients),
            "encounter_count": db.scalar(select(func.count()).select_from(Encounter)) or 0,
            "condition_count": len(conditions),
            "lab_count": db.scalar(select(func.count()).select_from(LabResult)) or 0,
            "vital_count": db.scalar(select(func.count()).select_from(Vital)) or 0,
            "prediction_log_count": db.scalar(select(func.count()).select_from(RiskPrediction)) or 0,
        }
        patient_ids_with_vitals = set(db.scalars(select(Vital.patient_id).distinct()))
        lab_rows_with_ranges = db.scalar(
            select(func.count()).select_from(LabResult).where(
                (LabResult.reference_low.is_not(None)) | (LabResult.reference_high.is_not(None))
            )
        ) or 0
        first_encounter, last_encounter = db.execute(
            select(func.min(Encounter.started_at), func.max(Encounter.started_at))
        ).one()
        _SNAPSHOT = {
            "cache": cache,
            "patients": patient_map,
            "rows": rows,
            "conditions": conditions,
            "active_conditions": active_conditions,
            "counts": counts,
            "data_quality": {
                "patients_without_vitals": max(0, counts["patient_count"] - len(patient_ids_with_vitals)),
                "pct_labs_with_reference_range": lab_rows_with_ranges / max(counts["lab_count"], 1) * 100,
            },
            "data_span": {
                "first_encounter": _as_json(first_encounter),
                "last_encounter": _as_json(last_encounter),
            },
        }
        return _SNAPSHOT


def _overview(snapshot: dict[str, Any]) -> dict[str, Any]:
    rows = snapshot["rows"]
    counts = _category_counts(rows)
    return {
        **snapshot["counts"],
        "category_counts": counts,
        "avg_risk": sum(row["risk_score"] for row in rows) / max(len(rows), 1),
        "model_version": MODEL_VERSION,
        "weights": {"own_risk": 0.6, "neighbor_fraction": 0.4},
        "thresholds": {"moderate": 0.33, "high": 0.66, "high_risk_label": 0.5},
        "data_span": snapshot["data_span"],
        "data_quality": snapshot["data_quality"],
    }


def _group_summary(rows: list[dict[str, Any]], key: str) -> dict[str, dict[str, Any]]:
    groups: dict[str, list[dict[str, Any]]] = {}
    for row in rows:
        label = str(row.get(key) or "unknown")
        groups.setdefault(label, []).append(row)
    return {
        label: {
            "n": len(group),
            "avg_risk": sum(item["risk_score"] for item in group) / len(group),
            "category_counts": _category_counts(group),
        }
        for label, group in sorted(groups.items(), key=lambda item: item[0].lower())
    }


def _results(snapshot: dict[str, Any], db: Session) -> dict[str, Any]:
    rows = snapshot["rows"]
    cache = snapshot["cache"]
    bins = [{"range": f"{index / 10:.1f}-{(index + 1) / 10:.1f}", "start": index / 10, "end": (index + 1) / 10, "count": 0} for index in range(10)]
    for row in rows:
        index = min(9, int(row["risk_score"] * 10))
        bins[index]["count"] += 1

    age_buckets = [("0-17", 0, 17), ("18-34", 18, 34), ("35-49", 35, 49), ("50-64", 50, 64), ("65-79", 65, 79), ("80+", 80, None)]
    by_age = {}
    for label, lower, upper in age_buckets:
        group = [row for row in rows if row["age"] >= lower and (upper is None or row["age"] <= upper)]
        by_age[label] = {
            "n": len(group),
            "avg_risk": sum(row["risk_score"] for row in group) / max(len(group), 1),
            "category_counts": _category_counts(group),
        }

    active_conditions = snapshot["active_conditions"]
    top_conditions = []
    risks = {row["id"]: row["risk_score"] for row in rows}
    for display, patient_ids in sorted(active_conditions.items(), key=lambda item: (-len(item[1]), item[0].lower()))[:10]:
        top_conditions.append({
            "display": display,
            "patients": len(patient_ids),
            "avg_risk": sum(risks.get(patient_id, 0.0) for patient_id in patient_ids) / len(patient_ids),
        })

    measure_specs = [(name, name, limits) for name, limits in VITAL_RANGES.items()]
    measure_specs.extend((meta["name"], code, meta) for code, meta in LAB_RANGES.items())
    frequency = []
    observations = cache["latest_observations"]
    for measure, source_key, limits in measure_specs:
        available = 0
        out_count = 0
        for values in observations.values():
            value = values.get(source_key)
            if value is None:
                continue
            available += 1
            if (limits.get("low") is not None and value < limits["low"]) or (limits.get("high") is not None and value > limits["high"]):
                out_count += 1
        frequency.append({
            "measure": measure,
            "patients_with_data": available,
            "patients_out_of_range": out_count,
            "pct": out_count / max(available, 1) * 100,
        })
    frequency.sort(key=lambda item: (-item["pct"], item["measure"]))

    sample_size = min(300, len(rows))
    stride = max(1, math.ceil(len(rows) / max(sample_size, 1)))
    components = [
        {
            "own_risk": row["own_risk"],
            "neighbor_fraction": row["neighbor_fraction"],
            "category": row["risk_category"],
        }
        for row in rows[::stride][:300]
    ]
    top_risk = sorted(rows, key=lambda row: (-row["risk_score"], str(row["id"])))[:10]
    top_risk_patients = [{
        "patient_id": str(row["id"]),
        "mrn": row["mrn"],
        "age": row["age"],
        "sex": row["sex"],
        "risk_score": row["risk_score"],
        "risk_category": row["risk_category"],
        "top_out_of_range": [item["measure"] for item in row["out_of_range"][:3]],
    } for row in top_risk]

    prediction_rows = db.execute(
        select(RiskPrediction, Patient.mrn)
        .join(Patient, Patient.id == RiskPrediction.patient_id)
        .order_by(RiskPrediction.predicted_at.desc())
        .limit(10)
    ).all()
    recent_predictions = [{
        "patient_id": str(prediction.patient_id),
        "mrn": mrn or "",
        "risk_score": float(prediction.risk_score),
        "risk_category": prediction.risk_category,
        "model_version": prediction.model_version,
        "predicted_at": _as_json(prediction.predicted_at),
    } for prediction, mrn in prediction_rows]

    return {
        "patients_with_out_of_range": sum(bool(row["out_of_range"]) for row in rows),
        "score_histogram": bins,
        "by_age": by_age,
        "by_sex": _group_summary(rows, "sex"),
        "by_smoking": {
            status: _group_summary(rows, "smoking_status").get(status, {
                "n": 0,
                "avg_risk": 0.0,
                "category_counts": {"low": 0, "moderate": 0, "high": 0},
            })
            for status in ("never", "former", "current", "unknown")
        },
        "by_ethnicity": _group_summary(rows, "ethnicity"),
        "top_conditions": top_conditions,
        "out_of_range_frequency": frequency,
        "score_components_sample": components,
        "top_risk_patients": top_risk_patients,
        "recent_predictions": recent_predictions,
    }


